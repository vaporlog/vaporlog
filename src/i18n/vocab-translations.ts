/**
 * Returns the Spanish translation of a controlled tag when the UI language
 * is Spanish; anything else passes through unchanged.
 */
export function translateTag(tag: string, lang: string): string {
  if (!lang.startsWith("es")) return tag;
  return VOCAB_ES[tag] ?? tag;
}
